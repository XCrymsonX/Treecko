export const collectionStats = {
  total: treeckoCards.length,

  owned: treeckoCards.filter((card) => card.owned).length,

  hunting: treeckoCards.filter((card) => card.status === "HUNTING").length,

  grails: treeckoCards.filter((card) => card.grail).length,

  totalCopiesOwned: treeckoCards.reduce(
    (total, card) => total + card.quantity,
    0
  ),

  completionPercentage:
    treeckoCards.length === 0
      ? 0
      : Math.round(
          (treeckoCards.filter((card) => card.owned).length /
            treeckoCards.length) *
            1000
        ) / 10,
};

// -------------------------------------------------------
// HELPER FUNCTIONS
// -------------------------------------------------------

export function getOwnedCards() {
  return treeckoCards.filter((card) => card.owned);
}

export function getHuntingCards() {
  return treeckoCards.filter((card) => card.status === "HUNTING");
}

export function getGrailCards() {
  return treeckoCards.filter((card) => card.grail);
}

export function getCardsBySet(set: string) {
  return treeckoCards.filter((card) => card.set === set);
}

export function getCardsByYear(year: number) {
  return treeckoCards.filter((card) => card.year === year);
}

export function getCardsByLanguage(language: string) {
  return treeckoCards.filter((card) => card.language === language);
}

export function getCardById(id: string) {
  return treeckoCards.find((card) => card.id === id);
}